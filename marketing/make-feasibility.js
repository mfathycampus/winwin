function table(headers, rows, widths, { headBg = HEADBG } = {}) {
  const bd = { style: BorderStyle.SINGLE, size: 1, color: 'B4C4BC' };
  const borders = { top: bd, bottom: bd, left: bd, right: bd };
  const cell = (text, { head = false, w, bold = false, fill } = {}) => new TableCell({
    width: { size: w, type: WidthType.DXA }, borders,
    shading: { fill: head ? headBg : (fill || 'FFFFFF'), type: ShadingType.CLEAR },
    margins: { top: 70, bottom: 70, left: 100, right: 100 },
    children: [new Paragraph({ bidirectional: true, alignment: AlignmentType.START,
      children: [t(String(text), { bold: head || bold, color: head ? 'FFFFFF' : '111111', size: 20 })] })],
  });
  return new Table({
    visuallyRightToLeft: true, width: { size: CW, type: WidthType.DXA }, columnWidths: widths,
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, { head: true, w: widths[i] })) }),
      ...rows.map((r) => new TableRow({ children: r.map((c, i) =>
        cell(typeof c === 'object' ? c.v : c, { w: widths[i], bold: c.bold, fill: c.fill })) })),
    ],
  });
}

// Callout box
function box(title, lines, fill = LIGHT, accent = GREEN) {
  const bd = { style: BorderStyle.SINGLE, size: 4, color: accent };
  return new Table({
    visuallyRightToLeft: true, width: { size: CW, type: WidthType.DXA }, columnWidths: [CW],
    rows: [new TableRow({ children: [new TableCell({
      width: { size: CW, type: WidthType.DXA }, borders: { top: bd, bottom: bd, left: bd, right: bd },
      shading: { fill, type: ShadingType.CLEAR }, margins: { top: 110, bottom: 110, left: 150, right: 150 },
      children: [
        ...(title ? [new Paragraph({ bidirectional: true, spacing: { after: 70 }, children: [t(title, { bold: true, color: NAVY, size: 22 })] })] : []),
        ...lines.map((l) => new Paragraph({ bidirectional: true, spacing: { after: 50, line: 280 }, children: [t(l, { size: 20 })] })),
      ],
    })] })],
  });
}

